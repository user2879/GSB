GLYPH_ORDER = tuple(_RAW.keys())


def glyph_bitmap(name: str) -> list[list[int]]:
    if name not in _RAW:
        raise KeyError(f"未内置字模: {name}")
    rows = _RAW[name]
    if len(rows) != 12 or any(len(row) != 12 for row in rows):
        raise AssertionError(f"字模 {name} 尺寸不合规")
    return [[1 if cell == "#" else 0 for cell in row] for row in rows]


def scale_bitmap(bitmap: list[list[int]], factor: int) -> list[list[int]]:
    """最近邻整数倍放大，保持确定性。"""
    out: list[list[int]] = []
    for row in bitmap:
        wide: list[int] = []
        for cell in row:
            wide.extend([cell] * factor)
        for _ in range(factor):
            out.append(wide.copy())
    return out
