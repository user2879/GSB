from __future__ import annotations

import hashlib
from dataclasses import dataclass

import numpy as np

from .canonical import canonical_bytes, field_bytes, sha256_hex, uint32


@dataclass(frozen=True)
class ArtifactContent:
    node_id: str
    artifact_key: str
    shards: tuple[bytes, ...]
    digest: str


def _rng_seed(node_id: str, artifact_key: str, seed: int) -> int:
    material = b"CACHELEASE-CONTENT-SEED-v1\0" + field_bytes(node_id) + field_bytes(
        artifact_key
    ) + field_bytes(str(seed))
    return int.from_bytes(hashlib.sha256(material).digest(), "big")


def generate_content(
    node_id: str, artifact_key: str, seed: int, shard_count: int, shard_bytes: int
) -> ArtifactContent:
    """Generate node-local shard bytes with an explicit, reproducible combination rule.

    Each shard is generated by a PCG64 stream derived solely from the node id, artifact
    key and declared integer seed. Shards are emitted in ascending integer order.
    The final digest commits to the headers and every shard digest in that order.
    """

    rng = np.random.Generator(np.random.PCG64(_rng_seed(node_id, artifact_key, seed)))
    shards: list[bytes] = []
    combined = hashlib.sha256()
    combined.update(b"CACHELEASE-ARTIFACT-MANIFEST-v1\0")
    combined.update(field_bytes(node_id))
    combined.update(field_bytes(artifact_key))

    for shard_index in range(shard_count):
        values = rng.integers(0, 256, size=shard_bytes, dtype=np.uint8)
        payload = values.tobytes()
        shards.append(payload)

        shard_hash = hashlib.sha256()
        shard_hash.update(b"CACHELEASE-ARTIFACT-SHARD-v1\0")
        shard_hash.update(field_bytes(node_id))
        shard_hash.update(field_bytes(artifact_key))
        shard_hash.update(uint32(shard_index))
        shard_hash.update(uint32(len(payload)))
        shard_hash.update(payload)
        shard_digest = shard_hash.digest()
        combined.update(uint32(shard_index))
        combined.update(shard_digest)

    content = ArtifactContent(
        node_id=node_id,
        artifact_key=artifact_key,
        shards=tuple(shards),
        digest=combined.hexdigest(),
    )
    return content


def content_fingerprint(node_id: str, artifact_key: str, digest: str) -> str:
    return sha256_hex(
        canonical_bytes(
            {
                "domain": "CACHELEASE-CONTENT-FINGERPRINT-v1",
                "node_id": node_id,
                "artifact_key": artifact_key,
                "digest": digest,
            }
        )
    )
