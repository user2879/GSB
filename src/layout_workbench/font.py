@lru_cache(maxsize=1)
def font_templates() -> dict[str, np.ndarray]:
    templates: dict[str, np.ndarray] = {}
    for char, rows in _ROWS.items():
        raw = np.array([[1 if pixel == "1" else 0 for pixel in row] for row in rows], dtype=np.uint8)
        ys, xs = np.nonzero(raw)
        if len(ys) == 0:
            raise RuntimeError(f"empty font glyph: {char!r}")
        templates[char] = raw[ys.min() : ys.max() + 1, xs.min() : xs.max() + 1].copy()
    return templates


def template_version_info() -> dict[str, object]:
    templates = font_templates()
    return {
        "version": FONT_VERSION,
        "characters": sorted(templates),
        "count": len(templates),
    }

