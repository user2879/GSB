"""Generate deterministic local tables and the img2img starter image."""

from __future__ import annotations

import hashlib
import math
import struct
from pathlib import Path

import yaml


ROOT = Path(__file__).resolve().parents[1]
SAMPLES = ROOT / "samples"
DENOISE_STEPS = 6


def unit(domain: str, index: int, salt: str) -> float:
    digest = hashlib.sha256(f"{domain}|{index}|{salt}".encode("utf-8")).digest()
    return int.from_bytes(digest[:8], "big") / float(1 << 64)


def main() -> None:
    SAMPLES.mkdir(parents=True, exist_ok=True)
    noise = [round(0.10 + 0.26 * unit("noise", index, "renderlab"), 12) for index in range(DENOISE_STEPS)]
    guidance = [round(0.28 + 0.30 * unit("guidance", index, "renderlab"), 12) for index in range(DENOISE_STEPS)]
    (SAMPLES / "noise_table.yaml").write_text(
        "# Generated by scripts/generate_inputs.py\n"
        + yaml.safe_dump({"values": noise}, sort_keys=False),
        encoding="utf-8",
    )
    (SAMPLES / "guidance_table.yaml").write_text(
        "# Generated by scripts/generate_inputs.py\n"
        + yaml.safe_dump({"values": guidance}, sort_keys=False),
        encoding="utf-8",
    )

    width = height = 16
    body = bytearray()
    for row in range(height):
        for column in range(width):
            checker = 46 if (row // 4 + column // 4) % 2 == 0 else 0
            body.extend(
                (
                    (83 + 7 * row + checker) % 256,
                    (145 + 5 * column + checker) % 256,
                    (196 + 3 * (row + column) + checker) % 256,
                )
            )
    ppm = f"P6\n{width} {height}\n255\n".encode("ascii") + bytes(body)
    (SAMPLES / "initial.ppm").write_bytes(ppm)

    assert len(noise) == DENOISE_STEPS
    assert len(guidance) == DENOISE_STEPS
    assert all(math.isfinite(value) for value in noise + guidance)
    print(f"noise_table={len(noise)} guidance_table={len(guidance)} initial={width}x{height}")


if __name__ == "__main__":
    main()
