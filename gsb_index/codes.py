@dataclass
class Issue:
    """One deterministic business failure record."""

    code: str
    message: str
    object_type: str
    object_id: str
    field: str = ""
    details: dict[str, Any] = dataclass_field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        result = asdict(self)
        if not result["field"]:
            result.pop("field")
        if not result["details"]:
            result.pop("details")
        return result


def issue_sort_key(item: dict[str, Any]) -> tuple:
    return (
        str(item.get("code", "")),
        str(item.get("object_type", "")),
        str(item.get("object_id", "")),
        str(item.get("field", "")),
        str(item.get("message", "")),
    )
