def get_observer(key: str) -> Observer:
    try:
        return OBSERVERS[key]
    except KeyError:
        raise DiagnosticError(
            code=ErrorCode.OBSERVER_INVALID,
            message=f"unknown observer marker: {key!r}",
            details={
                "observer": key,
                "allowed": sorted(OBSERVERS),
                "sample_index": 0,
                "component": 0,
                "component_name": "X",
                "observation_kind": "observer_marker",
            },
        ) from None
